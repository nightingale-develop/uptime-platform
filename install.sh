#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

unset COMPOSE_FILE COMPOSE_PROJECT_NAME COMPOSE_PROFILES COMPOSE_ENV_FILES COMPOSE_PATH_SEPARATOR
unset APP_IMAGE FRONTEND_IMAGE FRONTEND_PORT POSTGRES_DB POSTGRES_USER POSTGRES_PASSWORD
unset JWT_SECRET JWT_ACCESS_TOKEN_TTL_MINUTES API_KEY_HASH_SECRET REFRESH_TOKEN_HASH_SECRET
unset REFRESH_TOKEN_TTL_DAYS REFRESH_COOKIE_NAME REFRESH_COOKIE_SECURE REFRESH_COOKIE_SAMESITE
unset CORS_ALLOWED_ORIGINS NOTIFICATION_TIMEOUT_SECONDS UPTIME_HOST PUBLIC_APP_URL
unset RETENTION_ENABLED RETENTION_CHECKS_DAYS RETENTION_INCIDENTS_DAYS
unset RETENTION_NOTIFICATIONS_DAYS RETENTION_INTERVAL_SECONDS RETENTION_BATCH_SIZE

RELEASE_VERSION=latest
RELEASE_BASE=https://raw.githubusercontent.com/nightingale-develop/uptime-platform
INSTALL_DIR=/opt/uptime-platform
LOCK_FILE=/run/lock/uptime-platform.lock
PROJECT_NAME=uptime-platform
MANAGED_MARKER='# Managed by Uptime Platform install.sh'
CLEAN=0
stage=

fail() {
  printf '\nERROR: %s\n' "$*" >&2
  exit 1
}

while (($#)); do
  case "$1" in
    --clean) CLEAN=1; shift ;;
    --help)
      printf 'Usage: sudo bash install.sh [--clean]\n'
      printf 'Installs into /opt/uptime-platform. --clean deletes this installation and all Docker resources labelled as project uptime-platform, including database, monitoring and certificate volumes.\n'
      exit 0
      ;;
    *) fail "Unknown argument: $1" ;;
  esac
done

[[ $EUID -eq 0 ]] || fail 'Run with sudo: sudo bash install.sh'
[[ -t 0 ]] || fail 'An interactive terminal is required.'
for executable in docker curl openssl python3 getent mktemp flock awk; do
  command -v "$executable" >/dev/null 2>&1 || fail "Missing dependency: $executable"
done
[[ ! -L "$INSTALL_DIR" ]] || fail "$INSTALL_DIR must not be a symlink."
[[ ! -e "$INSTALL_DIR" || -d "$INSTALL_DIR" ]] || fail "$INSTALL_DIR is not a directory."
[[ ! -L "$LOCK_FILE" ]] || fail 'Refusing a symlink at the installation lock.'
exec 9>"$LOCK_FILE"
flock -n 9 || fail 'Another installation or update is running.'
trap '[[ -z "$stage" ]] || rm -rf -- "$stage"' EXIT

docker info >/dev/null 2>&1 || fail 'Docker daemon is unavailable.'
docker compose version >/dev/null 2>&1 || fail 'Docker Compose v2 is required.'

if ((CLEAN == 0)); then
  for filename in .env compose.yml Caddyfile update.sh observability; do
    [[ ! -L "$INSTALL_DIR/$filename" ]] || fail "Refusing symlink $INSTALL_DIR/$filename"
  done
  if [[ -f "$INSTALL_DIR/.env" ]]; then
    grep -Fxq '# Generated by Uptime Platform install.sh' "$INSTALL_DIR/.env" || fail 'Existing configuration is not installer-managed. Use --clean for a fresh installation.'
    stage=$(mktemp -d /tmp/uptime-install.XXXXXXXX)
    curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 \
      --connect-timeout 15 --max-time 120 "$RELEASE_BASE/refs/tags/latest/update.sh" -o "$stage/update.sh"
    bash -n "$stage/update.sh"
    flock -u 9
    bash "$stage/update.sh"
    exit 0
  fi
  containers=$(docker ps -aq --filter "label=com.docker.compose.project=$PROJECT_NAME")
  volumes=$(docker volume ls -q --filter "label=com.docker.compose.project=$PROJECT_NAME")
  [[ -z "$containers$volumes" ]] || fail 'An old uptime-platform deployment exists. Use install.sh --clean to replace it.'
  [[ ! -e "$INSTALL_DIR/compose.yml" ]] || fail 'Incomplete installation found. Inspect it or use --clean.'
fi

classify_host() {
  if [[ "$1" == localhost || "$1" == 127.0.0.1 ]]; then
    printf 'local\n'
    return
  fi
  python3 - "$1" <<'PY'
import ipaddress
import re
import sys

host = sys.argv[1]
try:
    ipaddress.IPv4Address(host)
except ipaddress.AddressValueError:
    label = r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?"
    if len(host) > 253 or not re.fullmatch(rf"(?:{label}\.)+{label}", host):
        sys.exit(1)
    if re.fullmatch(r"[0-9.]+", host):
        sys.exit(1)
    print("domain")
else:
    print("ip")
PY
}

printf '\n=== Uptime Platform installer ===\nInstall location: %s\n' "$INSTALL_DIR"
while true; do
  read -r -p 'Address (localhost, domain, IPv4; blank = public IPv4): ' host || fail 'Input canceled.'
  if [[ -z "$host" ]]; then
    if ! host=$(curl --noproxy '*' -4fsS --max-time 10 https://api.ipify.org); then
      printf 'IP detection failed. Enter an address manually.\n' >&2
      continue
    fi
    printf 'Detected public outbound IP: %s\n' "$host"
  fi
  host="${host,,}"
  if ! host_kind=$(classify_host "$host"); then
    printf 'Enter localhost, a domain or an IPv4 without scheme, port or path.\n' >&2
    continue
  fi
  if [[ "$host_kind" == domain ]] && ! getent ahostsv4 "$host" >/dev/null; then
    printf 'Domain has no IPv4 DNS record. Check DNS.\n' >&2
    continue
  fi
  break
done
profiles=()
if [[ "$host_kind" == local ]]; then
  app_url="http://$host:8080"
else
  app_url="https://$host"
  profiles+=(--profile public)
  printf 'Ports 80 and 443 must be reachable.\n'
  [[ "$host_kind" != ip ]] || printf 'IP mode uses a private Caddy CA; clients must trust it.\n'
fi
printf '\nURL: %s\n' "$app_url"
if ((CLEAN)); then
  printf 'CLEAN INSTALL deletes all uptime-platform containers, volumes, networks and %s, including its backups. Other Docker projects and your source checkout are preserved.\n' "$INSTALL_DIR"
  read -r -p 'Confirm clean installation (CONFIRM): ' confirmation || fail 'Input canceled.'
  [[ "$confirmation" == 'CONFIRM' ]] || fail 'Clean installation canceled. Nothing was deleted.'
else
  read -r -p 'Continue? [y/N]: ' confirmation || fail 'Input canceled.'
  [[ "$confirmation" == [yY] ]] || fail 'Installation canceled.'
fi

stage=$(mktemp -d /tmp/uptime-install.XXXXXXXX)
release_files=(
  compose.yml
  .env.example
  observability/prometheus/prometheus.yml
  observability/prometheus/alerts.yml
  observability/prometheus/alerts.test.yml
  observability/grafana/provisioning/datasources/prometheus.yml
  observability/grafana/provisioning/dashboards/uptime.yml
  observability/grafana/dashboards/uptime-platform.json
)
for file in "${release_files[@]}"; do
  mkdir -p -- "$stage/$(dirname "$file")"
  curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 \
    --connect-timeout 15 --max-time 120 "$RELEASE_BASE/refs/tags/latest/$file" -o "$stage/$file" || \
    fail "Could not download $file from latest. Nothing was deleted."
done
curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 \
  --connect-timeout 15 --max-time 120 "$RELEASE_BASE/refs/tags/latest/update.sh" -o "$stage/update.sh"
bash -n "$stage/update.sh"
{ printf '%s\n' "$MANAGED_MARKER"; cat "$stage/compose.yml"; } > "$stage/compose.managed.yml"
mv "$stage/compose.managed.yml" "$stage/compose.yml"
{
  printf '# Generated by Uptime Platform install.sh\nUPTIME_HOST=%s\n' "$host"
  for key in POSTGRES_PASSWORD JWT_SECRET API_KEY_HASH_SECRET REFRESH_TOKEN_HASH_SECRET; do
    printf '%s=%s\n' "$key" "$(openssl rand -hex 32)"
  done
  if [[ "$host_kind" == local ]]; then
    printf 'REFRESH_COOKIE_SECURE=false\n'
  else
    printf 'REFRESH_COOKIE_SECURE=true\n'
    if [[ "$host_kind" == domain && "$host" != *.internal && "$host" != *.local && "$host" != *.localhost ]] ||
       { [[ "$host_kind" == ip ]] && python3 -c 'import ipaddress,sys; sys.exit(not ipaddress.ip_address(sys.argv[1]).is_global)' "$host"; }; then
      printf 'PUBLIC_APP_URL=%s\n' "$app_url"
    fi
  fi
  printf 'CORS_ALLOWED_ORIGINS=%s\n' "$app_url"
  printf 'APP_IMAGE=sashastudent/uptime-platform:%s\n' "$RELEASE_VERSION"
  printf 'FRONTEND_IMAGE=sashastudent/uptime-platform-frontend:%s\n' "$RELEASE_VERSION"
} > "$stage/.env"
awk '
  /^[[:space:]]*(export[[:space:]]+)?[A-Za-z_][A-Za-z0-9_]*[[:space:]]*=/ {
    key = $0
    sub(/^[[:space:]]*(export[[:space:]]+)?/, "", key)
    sub(/[[:space:]]*=.*/, "", key)
    if (FNR == NR) seen[key] = 1
    else if (!seen[key]++) {
      if (key == "DATABASE_URL") database_url = 1
      else print
    }
  }
  FNR == NR { print }
  END {
    if (database_url)
      print "DATABASE_URL=postgresql+asyncpg://${POSTGRES_USER}:${POSTGRES_PASSWORD}@postgres:5432/${POSTGRES_DB}"
  }
' "$stage/.env" "$stage/.env.example" > "$stage/env.new"
mv "$stage/env.new" "$stage/.env"
if [[ "$host_kind" != local ]]; then
  {
    printf '# Generated by Uptime Platform install.sh\n'
    [[ "$host_kind" != ip ]] || printf '{\n    default_sni %s\n}\n\n' "$host"
    printf '%s {\n' "$host"
    [[ "$host_kind" != ip ]] || printf '    tls internal\n'
    printf '    reverse_proxy frontend:8080\n}\n'
  } > "$stage/Caddyfile"
fi
staged() {
  docker compose --project-name "$PROJECT_NAME" --project-directory "$stage" \
    --env-file "$stage/.env" -f "$stage/compose.yml" "${profiles[@]}" "$@"
}
staged config --quiet
printf '\nDownloading images before changing the existing installation...\n'
staged pull --policy always
staged run --rm -T --no-deps api python -c 'import uptime_platform.main' >/dev/null

if ((CLEAN)); then
  containers=$(docker ps -aq --filter "label=com.docker.compose.project=$PROJECT_NAME")
  [[ -z "$containers" ]] || docker rm -f $containers
  volumes=$(docker volume ls -q --filter "label=com.docker.compose.project=$PROJECT_NAME")
  [[ -z "$volumes" ]] || docker volume rm $volumes
  networks=$(docker network ls -q --filter "label=com.docker.compose.project=$PROJECT_NAME")
  [[ -z "$networks" ]] || docker network rm $networks
  rm -rf -- "$INSTALL_DIR"
fi

mkdir -p -- "$INSTALL_DIR"
cp -a "$stage/." "$INSTALL_DIR/"
chmod 755 "$INSTALL_DIR"
find "$INSTALL_DIR/observability" -type d -exec chmod 755 {} +
find "$INSTALL_DIR/observability" -type f -exec chmod 644 {} +
chmod 600 "$INSTALL_DIR/.env"
chmod 644 "$INSTALL_DIR/compose.yml"
chmod 755 "$INSTALL_DIR/update.sh"
[[ ! -f "$INSTALL_DIR/Caddyfile" ]] || chmod 644 "$INSTALL_DIR/Caddyfile"
compose() {
  docker compose --project-name "$PROJECT_NAME" --project-directory "$INSTALL_DIR" \
    --env-file "$INSTALL_DIR/.env" -f "$INSTALL_DIR/compose.yml" "${profiles[@]}" "$@"
}
compose up -d --no-build --wait api
compose up -d --no-build --wait frontend scheduler notification-worker
[[ "$host_kind" == local ]] || compose up -d --no-build --wait caddy

curl_opts=(--noproxy '*' --fail --silent --show-error --max-time 6)
if [[ "$host_kind" == local ]]; then
  curl_opts+=(--resolve "$host:8080:127.0.0.1")
else
  curl_opts+=(--resolve "$host:443:127.0.0.1")
  [[ "$host_kind" != ip ]] || curl_opts+=(-k)
fi
ready=0
for attempt in {1..30}; do
  if curl "${curl_opts[@]}" "$app_url/" -o /dev/null 2>/dev/null &&
     curl "${curl_opts[@]}" "$app_url/backend/health" 2>/dev/null |
       python3 -c 'import json,sys; sys.exit(0 if json.load(sys.stdin).get("status") == "ok" else 1)' 2>/dev/null; then
    ready=1
    break
  fi
  sleep 2
done
((ready)) || fail "Health check failed. Inspect logs in $INSTALL_DIR. Installation data were retained."
printf '\nInstallation completed.\nURL: %s\nCreate your administrator account: %s/register\nConfiguration: %s\n' "$app_url" "$app_url" "$INSTALL_DIR"
